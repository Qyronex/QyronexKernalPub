use core::sync::atomic::{AtomicU8, Ordering};
use kernal_core_aarch64::{
    InitialLeaderPublishError, PublishedInitialLinuxLeader,
    publish_initial_linux_leader_with_core_stack,
};
use kernal_protected_boot_aarch64::{ProtectedInitrd, RuntimeTablePool};
use kernal_scheduler_cpu::CpuSchedulerCell;
use kernal_scheduler_smp::GlobalThreadId;
use kernal_user_elf_runtime_aarch64::LinuxProcessStart;

use super::{entropy, loader_frames, memory, runtime};

/// Fixed proof capacity for the unchanged static Linux image plus its canonical Linux stack.
///
/// The historical Step-15 musl fixture fit inside 512 frames (2 MiB). The pinned Step-28 Debian
/// static BusyBox image is itself just under 2 MiB before PT_LOAD BSS/page rounding and the four-page
/// initial Linux stack are accounted for, so that fixture-sized bound can reject the unchanged
/// Debian executable before allocation. Keep the production transaction fixed-capacity and
/// fail-closed, but give the Debian proof a still-small 3 MiB ceiling. Exact required pages are
/// computed and checked before the first frame is removed from the allocator.
const INITIAL_FRAME_CAPACITY: usize = 768;
const INITIAL_SEGMENTS: usize = 16;
const STEP28_PROOF_IDLE: u8 = 0;
const STEP28_ARCHIVE_SELECTED: u8 = 1;
const STEP28_LEADER_LOADED: u8 = 2;

/// One-boot proof state used by the feature-scoped Step-28/29/30 acceptance paths.
/// Transitions are monotonic and happen after the exact CPIO/ELF boundary and after canonical leader
/// publication. The final BSP-side lifecycle marker consumes only the completed state; it does not
/// grant loader or archive authority and is never consulted by the historical Step-15 direct-ELF
/// path.
static STEP28_PROOF_STATE: AtomicU8 = AtomicU8::new(STEP28_PROOF_IDLE);

#[derive(Debug)]
pub enum Error {
    Entropy(entropy::Error),
    Runtime(runtime::Error),
    FramePool(memory::Error),
    Loader(loader_frames::Error),
    Vm(kernal_linux_vm::Error),
    Leader(InitialLeaderPublishError),
    Initramfs,
}

pub(super) fn step28_proof_complete() -> bool {
    STEP28_PROOF_STATE.load(Ordering::Acquire) == STEP28_LEADER_LOADED
}

/// Preserves the accepted Step-15 direct-initrd loader entry while selecting a proof-scoped archive
/// executable only when the dedicated acceptance features are active. Step 28/29 continue to select
/// the pinned unchanged BusyBox image; Step 30 selects the ordinary static Linux proof executable
/// generated by `xtask` and then runs it unchanged through the same CPIO/ELF/Process path.
///
/// This is loader test-image selection, not runtime process-name policy. No syscall, scheduler,
/// Process, VFS, FD or signal code can observe this choice as authority.
///
/// # Safety
/// The caller must satisfy [`load_and_publish_image`]'s owner/quiescence contract.
pub unsafe fn load_and_publish<const SCHED_THREADS: usize, const WAKES: usize>(
    initrd: ProtectedInitrd,
    backend: &mut RuntimeTablePool,
    scheduler: &'static CpuSchedulerCell<SCHED_THREADS, WAKES>,
    priority: u8,
) -> Result<PublishedInitialLinuxLeader, Error> {
    if cfg!(feature = "step28-qemu-proof") {
        return initrd.with_bytes(|archive| {
            let parsed = kernal_cpio::Archive::parse(archive).map_err(|_| Error::Initramfs)?;
            let image_path: &[u8] = if cfg!(feature = "step30-final-qemu-proof") {
                b"bin/step30-proof"
            } else {
                b"bin/busybox"
            };
            let entry = parsed
                .get(image_path)
                .map_err(|_| Error::Initramfs)?
                .ok_or(Error::Initramfs)?;
            if !entry.is_regular_file() || entry.mode() & 0o111 == 0 {
                return Err(Error::Initramfs);
            }

            // Prove the exact selected archive member with the canonical AArch64 ELF parser before
            // publishing the archive boundary. The image borrow remains inside `with_bytes`.
            initrd
                .proof()
                .parse_initramfs_aarch64_elf(archive, image_path)
                .map_err(|_| Error::Initramfs)?;
            STEP28_PROOF_STATE
                .compare_exchange(
                    STEP28_PROOF_IDLE,
                    STEP28_ARCHIVE_SELECTED,
                    Ordering::AcqRel,
                    Ordering::Acquire,
                )
                .map_err(|_| Error::Initramfs)?;

            let image = entry.data();
            let argv0: &[u8] = if cfg!(feature = "step30-final-qemu-proof") {
                b"step30-proof"
            } else if cfg!(feature = "step29-fs-breadth-negative-qemu-proof") {
                b"fs-breadth-negative"
            } else if cfg!(feature = "step29-fs-breadth-qemu-proof") {
                b"fs-breadth-roundtrip"
            } else if cfg!(feature = "step29-directory-qemu-proof") {
                b"ls"
            } else if cfg!(feature = "step29-qemu-proof") {
                b"date"
            } else {
                b"true"
            };
            // SAFETY: the selected executable image borrow cannot escape `with_bytes`; the caller
            // owns the exact synchronous loader/backend/scheduler mutation window.
            let leader =
                unsafe { load_and_publish_image(image, argv0, backend, scheduler, priority) }?;
            STEP28_PROOF_STATE
                .compare_exchange(
                    STEP28_ARCHIVE_SELECTED,
                    STEP28_LEADER_LOADED,
                    Ordering::AcqRel,
                    Ordering::Acquire,
                )
                .map_err(|_| Error::Initramfs)?;
            Ok(leader)
        });
    }

    initrd.with_bytes(|image| {
        // SAFETY: the public function contract owns the same synchronous loader window and the byte
        // borrow cannot escape `ProtectedInitrd::with_bytes`.
        unsafe { load_and_publish_image(image, b"pthread_minimum", backend, scheduler, priority) }
    })
}

/// Loads one already-selected unchanged Linux ELF into the persistent Process, registers its exact
/// initial program break and transactionally publishes the first real EL0 scheduler generation.
///
/// The image borrow is consumed synchronously by the existing canonical AArch64 Linux loader. This
/// function does not parse CPIO, create another ELF loader, retain the source bytes, or change the
/// accepted Process/address-space ownership transaction. `argv0` is the only caller-selected process
/// start string supported by the existing bounded Linux stack ABI.
///
/// `AT_RANDOM` comes only from the one-shot QEMU DTB `/chosen/rng-seed` owner. The seed is consumed
/// before the loader transaction and is never synthesized or reused after a failure. Loader frames
/// come only from Core's sole persistent Step-15 frame pool. On successful load they remain
/// Process-owned. If break registration or later leader publication fails, this boot path fails
/// closed and does not speculate that mapped image frames, VM metadata or scheduler state are safe to
/// recycle under another owner.
///
/// # Safety
/// The caller must run on `scheduler`'s owner PE with local IRQ delivery masked, irq_depth=0,
/// preempt_count=0 and migration suppressed. `backend` must be the exact construction-window
/// RuntimeTablePool cursor supplied by protected boot. No operation in this function may block or
/// context-switch; every runtime/frame/backend borrow ends before return.
pub unsafe fn load_and_publish_image<const SCHED_THREADS: usize, const WAKES: usize>(
    image: &[u8],
    argv0: &[u8],
    backend: &mut RuntimeTablePool,
    scheduler: &'static CpuSchedulerCell<SCHED_THREADS, WAKES>,
    priority: u8,
) -> Result<PublishedInitialLinuxLeader, Error> {
    let random = entropy::take_at_random().map_err(Error::Entropy)?;
    let start = LinuxProcessStart::new(argv0, random);

    let loaded = runtime::with_linux_runtime(|state| {
        let (process, objects, space) = state.loader_parts();
        memory::with_live_frame_pool(|pool| {
            // SAFETY: the public function contract owns the exact Process/address-space/backend
            // mutation window. The nested frame-pool/runtime borrows are synchronous and cannot
            // escape this closure or survive a scheduler switch.
            unsafe {
                loader_frames::load_initial_linux_elf_with_core_frames::<
                    INITIAL_FRAME_CAPACITY,
                    INITIAL_SEGMENTS,
                    { runtime::STEP15_RUNTIME_CAPS },
                    { runtime::STEP15_RUNTIME_OBJECTS },
                    { runtime::STEP15_RUNTIME_VMAS },
                    RuntimeTablePool,
                >(image, start, pool, process, objects, space, backend)
            }
        })
    });

    let loaded = loaded
        .map_err(Error::Runtime)?
        .map_err(Error::FramePool)?
        .map_err(Error::Loader)?;

    runtime::with_linux_runtime(|state| {
        // Register exactly the unrounded highest PT_LOAD memory end retained by the canonical loader.
        // If a later leader-publication rollback exits the Process, boot still fails closed; this
        // one-process proof never recycles the now-stale VM-break slot into another identity.
        state
            .register_initial_break(loaded.initial_break)
            .map_err(Error::Vm)?;

        let leader = {
            let (process, address_space, objects, bindings, identities, exits) =
                state.initial_leader_parts();
            // SAFETY: delegated owner/quiescence contract is exactly the initial leader publisher's
            // contract. The loader transaction and all frame/backend borrows ended above; publication
            // stages the generation Ready but performs no context switch or user execution here.
            unsafe {
                publish_initial_linux_leader_with_core_stack(
                    loaded.loaded,
                    process,
                    address_space,
                    objects,
                    bindings,
                    identities,
                    exits,
                    scheduler,
                    priority,
                )
            }
            .map_err(Error::Leader)?
        };

        // The leader is Ready but cannot run until the later explicit resume/yield boundary. Bind its
        // per-thread signal state now, while this same boot transaction still owns the IRQ-masked
        // scheduler window. Failure is fail-stop: no EL0 execution or retry is permitted with a Ready
        // generation lacking canonical SignalTable state.
        let owner = scheduler
            .owner()
            .map_err(|error| Error::Leader(InitialLeaderPublishError::Scheduler(error)))?;
        state
            .bind_initial_signal_thread(GlobalThreadId::new(owner, leader.scheduler_thread()))
            .map_err(Error::Runtime)?;
        Ok(leader)
    })
    .map_err(Error::Runtime)?
}
